def find_centile(row, col, df_ref):
    match = df_ref[df_ref['Возраст'] == row['возраст_6мес']]
    if match.empty:
        return np.nan
    w = row[col]
    c3, c10, c25, c50 = match.iloc[0]['3_Центили'], match.iloc[0]['10_Центили'], match.iloc[0]['25_Центили'], match.iloc[0]['50_Центили']
    c75, c90, c97 = match.iloc[0]['75_Центили'], match.iloc[0]['90_Центили'], match.iloc[0]['97_Центили']
    if w < c50:
        if w < c25:
            return 10 if w < c10 else 25
        return 25
    elif w > c50:
        if w < c75:
            return 50
        elif w < c90:
            return 75
        elif w < c97:
            return 90
        else:
            return 97
    elif w < c10:
        return 3 if w <= c3 else 10
    return None


def label_encode(X):
    enc = LabelEncoder()
    X_enc = X.copy()
    cat_cols = X.select_dtypes(include=['category', 'object']).columns.tolist()
    for col in cat_cols:
        X_enc[col] = enc.fit_transform(X[col].astype('str'))
    new_df = pd.concat([X_enc[cat_cols], X.drop(columns=cat_cols)], axis=1)
    return new_df.reindex(sorted(new_df.columns), axis=1)


def _error_html(msg):
    return (f'<div style="padding:20px;background:#fff5f5;border-left:4px solid #e53e3e;'
            f'border-radius:8px;color:#742a2a;font-family:sans-serif;">'
            f'❌ <b>Ошибка:</b> {msg}</div>')


