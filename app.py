def predict(пол, возраст, вес, рост, бса, сопвпс, гествозраст, О2капиляр, одышцианприст,
            фвлжпервич, кдрлж, ксрлж, кдолж, устьеПЛА, УстьеЛЛА, ствол_ла, фк_ла,
            створкиклЛА, градиентдавленияпжла, дмжпмм, давлениеПЖ, ЛАИ, ABнАо):

    display_dict = {
        'Пол': 'Мужской' if пол == 1 else 'Женский',
        'Возраст (дни)': возраст, 'Вес (кг)': вес, 'Рост (см)': рост,
        'БСА': бса, 'Сопутствующие ВПС': сопвпс or '—',
        'Гестационный возраст (дни)': гествозраст,
        'SpO₂ (%)': О2капиляр,
        'Одышка/цианоз': 'Есть' if одышцианприст == 2 else 'Нет',
        'ФВ ЛЖ (%)': фвлжпервич, 'КДР ЛЖ (см)': кдрлж, 'КСР ЛЖ (см)': ксрлж,
        'КДО ЛЖ (мм)': кдолж, 'Устье ПЛА (мм)': устьеПЛА, 'Устье ЛЛА (мм)': УстьеЛЛА,
        'Ствол ЛА (мм)': ствол_ла, 'ФК ЛА (мм)': фк_ла,
        'Створки ЛА': створкиклЛА or '—',
        'Градиент ПЖ/ЛА': градиентдавленияпжла,
        'ДМЖП (мм)': дмжпмм, 'Давление ПЖ': давлениеПЖ,
        'ЛАИ': ЛАИ, 'ABнАо': ABнАо,
    }
    display_df = pd.DataFrame(list(display_dict.items()), columns=['Параметр', 'Значение'])

    if MODEL is None:
        return display_df, _error_html(
            f'Модель не загружена. Проверьте, что model.pkl лежит рядом с app.py. '
            f'({MODEL_ERROR})'
        )

    try:
        вес_effective = 0 if возраст < 75 else 1

        df = pd.DataFrame([{
            'пол': пол, 'возраст': возраст, 'вес': вес_effective, 'рост': рост,
            'бса': бса, 'сопвпс': сопвпс or '', 'гествозраст': гествозраст,
            'О2капиляр': О2капиляр, 'одышцианприст': одышцианприст,
            'фвлжпервич': фвлжпервич, 'кдрлж': кдрлж, 'ксрлж': ксрлж,
            'кдолж': кдолж, 'устьеПЛА': устьеПЛА, 'УстьеЛЛА': УстьеЛЛА,
            'ствол_ла': ствол_ла, 'фк_ла': фк_ла, 'створкиклЛА': створкиклЛА or '',
            'градиентдавленияпжла': градиентдавленияпжла, 'дмжпмм': дмжпмм,
            'давлениеПЖ': давлениеПЖ, 'ЛАИ': ЛАИ, 'ABнАо': ABнАо,
        }])

        df[['пол', 'одышцианприст']] = df[['пол', 'одышцианприст']].astype('category')
        df['log'] = np.log((df['ABнАо'] * df['ЛАИ']) + 1e-9)
        df['одышцианприст'] = df['одышцианприст'].replace({2: 1, 1: 0}).astype(int)

        s = df['створкиклЛА'].fillna('')
        df['створки_удлинены']  = s.str.contains('длин', case=False).astype(int)
        df['створки_уплотнены'] = s.str.contains('плот', case=False).astype(int)
        df['створки_сращены']   = s.str.contains('сращ', case=False).astype(int)
        df['створки_неподв']    = s.str.contains('гранич', case=False).astype(int)
        df['аномал_отв']        = s.str.contains('отв', case=False).astype(int)

        gv = df['гествозраст'].iloc[0]
        df['Недонош'] = 1 if pd.notna(gv) and gv < 35 else (0 if pd.notna(gv) else -1)

        df = df.drop(['створкиклЛА'], axis=1)

        v = int(возраст)
        bucket = -1
        for r in AGE_RANGES:
            if v <= int(r):
                bucket = int(r)
                break
        df['возраст_6мес'] = bucket

        df_weight = (pd.DataFrame(WEIGHT_CENTILE_DATA)
                     .replace(',', '.', regex=True).astype(float))
        df['центили_вес']  = df.apply(lambda x: find_centile(x, 'вес',  df_weight), axis=1)
        df['центили_рост'] = df.apply(lambda x: find_centile(x, 'рост', df_weight), axis=1)

        df['возр_мес'] = df['возраст'] / 30
        vm = df['возр_мес'].iloc[0]
        df['Новорожд']    = 1 if vm < 1 else 0
        df['Старше_года'] = 1 if vm > 12 else 0
        df['1мес_1год']   = 1 if (1 < vm <= 12) else 0

        df = df.drop(['возраст', 'возраст_6мес'], axis=1)
        df['сопвпс'] = 1 if (сопвпс and str(сопвпс).strip()) else 0
        df['градиентдавленияпжла'] = df['градиентдавленияпжла'].map(lambda x: x if x <= 100 else 100)

        df = label_encode(df)
        df = df.drop(['Новорожд', 'Недонош', 'Старше_года', 'гествозраст', 'рост', 'вес',
                      'сопвпс', 'створки_удлинены', 'створки_уплотнены', 'створки_сращены',
                      'створки_неподв', 'аномал_отв'], axis=1)

        pred = int(MODEL.predict(df)[0])
        name, emoji, gradient = RESULT_MAP[pred]
        result_html = f"""
        <div style="padding:28px 24px;background:{gradient};border-radius:16px;
                    color:white;text-align:center;box-shadow:0 10px 30px rgba(0,0,0,.18);
                    font-family:'Segoe UI',sans-serif;">
            <div style="font-size:52px;margin-bottom:10px;">{emoji}</div>
            <div style="font-size:12px;letter-spacing:3px;opacity:.92;
                        text-transform:uppercase;margin-bottom:10px;">
                Рекомендованная тактика
            </div>
            <div style="font-size:21px;font-weight:600;line-height:1.4;">{name}</div>
        </div>"""
        return display_df, result_html

    except Exception as e:
        print(f'[ERROR] {e}')
        traceback.print_exc()
        return display_df, _error_html(str(e))


